-- =====================================================================
-- PolyAd — base schema, in its own Postgres schema `polyad`.
--
-- PolyAd shares a Supabase project with Shryxa Ads (live). Everything lives
-- in schema `polyad` so the two apps never read or write each other's rows
-- (Shryxa's billing cron would otherwise pause PolyAd campaigns).
--
-- Mirrors Shryxa migrations 0001–0004 (see supabase/shryxa_reference/) minus
-- billing, plus the team model: users.owner_id → shared workspace.
--
-- After applying: Supabase dashboard → Project Settings → Data API →
-- "Exposed schemas" → add `polyad` (the app talks to it through PostgREST).
--
-- Security: RLS on every table with NO policies; only the service role
-- (server-side) can read or write.
-- =====================================================================

begin;

create schema if not exists polyad;
grant usage on schema polyad to service_role;
alter default privileges in schema polyad grant all on tables to service_role;
alter default privileges in schema polyad grant all on sequences to service_role;

-- ---------------------------------------------------------------- users
-- owner_id null = workspace owner (admin). Members point at their admin and
-- share every client/campaign in that workspace.
create table polyad.users (
  id             bigint generated by default as identity primary key,
  email          text not null unique,
  password_hash  text not null,
  is_admin       integer not null default 0 check (is_admin in (0, 1)),
  owner_id       bigint references polyad.users (id) on delete cascade,
  created_at     text not null
);
create index users_owner_id_idx on polyad.users (owner_id);

create table polyad.sessions (
  token       text primary key,
  user_id     bigint not null references polyad.users (id) on delete cascade,
  created_at  text not null,
  expires_at  text not null
);
create index sessions_user_id_idx on polyad.sessions (user_id);

-- -------------------------------------------------------------- clients
-- A client = one candidate or party with its own Meta ad account + Page.
create table polyad.clients (
  id                   bigint generated by default as identity primary key,
  user_id              bigint not null references polyad.users (id) on delete cascade,
  ad_account_id        text,
  page_id              text,
  business_name        text,
  created_at           text not null,
  service_model        text not null default 'agency_managed'
                       check (service_model in ('self_service', 'agency_managed')),
  billing_arrangement  text
                       check (billing_arrangement in ('management_fee_only', 'management_plus_ad_budget')),
  client_status        text not null default 'pending_access'
                       check (client_status in ('pending_access', 'active', 'paused')),
  is_self              boolean not null default false,
  meta_connection_id   bigint,
  ad_account_name      text,
  page_name            text,
  instagram_actor_id   text,
  instagram_username   text,
  pixel_id             text,
  pixel_name           text,
  assets_updated_at    timestamptz,
  unique (user_id, ad_account_id)
);
create index clients_user_id_idx on polyad.clients (user_id);
create unique index clients_one_self_per_user on polyad.clients (user_id) where is_self;

-- ----------------------------------------------------- meta_connections
create table polyad.meta_connections (
  id                      bigint generated by default as identity primary key,
  user_id                 bigint not null references polyad.users (id) on delete cascade,
  client_id               bigint unique references polyad.clients (id) on delete cascade,
  meta_user_id            text,
  meta_user_name          text,
  ad_account_id           text,
  ad_account_name         text,
  access_token_encrypted  text not null,
  token_expires_at        timestamptz,
  connected_at            timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  connection_status       text not null default 'connected'
                          check (connection_status in ('connected', 'expired', 'revoked', 'error')),
  source                  text not null default 'owner' check (source in ('owner', 'invite', 'business')),
  token_type              text not null default 'user' check (token_type in ('user', 'system_user')),
  granted_scopes          text[],
  meta_business_id        text
);
create index meta_connections_user_id_idx on polyad.meta_connections (user_id);
create index meta_connections_user_source_idx on polyad.meta_connections (user_id, source);

alter table polyad.clients
  add constraint clients_meta_connection_fk
  foreign key (meta_connection_id) references polyad.meta_connections (id) on delete set null;

create table polyad.client_invites (
  id          bigint generated by default as identity primary key,
  token_hash  text not null unique,
  user_id     bigint not null references polyad.users (id) on delete cascade,
  client_id   bigint not null references polyad.clients (id) on delete cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  used_at     timestamptz
);
create index client_invites_client_id_idx on polyad.client_invites (client_id);

create table polyad.meta_oauth_states (
  id          bigint generated by default as identity primary key,
  state_hash  text not null unique,
  user_id     bigint not null references polyad.users (id) on delete cascade,
  client_id   bigint references polyad.clients (id) on delete cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  flow        text not null default 'owner' check (flow in ('owner', 'invite', 'business')),
  invite_id   bigint references polyad.client_invites (id) on delete cascade
);
create index meta_oauth_states_expires_idx on polyad.meta_oauth_states (expires_at);

create table polyad.meta_oauth_pending (
  id                      bigint generated by default as identity primary key,
  ticket_hash             text not null unique,
  user_id                 bigint not null references polyad.users (id) on delete cascade,
  client_id               bigint not null references polyad.clients (id) on delete cascade,
  meta_user_id            text,
  meta_user_name          text,
  accounts                jsonb not null,
  access_token_encrypted  text not null,
  token_expires_at        timestamptz,
  created_at              timestamptz not null default now(),
  expires_at              timestamptz not null
);

-- ------------------------------------------------------------ campaigns
create table polyad.campaigns (
  id                 bigint generated by default as identity primary key,
  user_id            bigint not null references polyad.users (id) on delete cascade,
  client_id          bigint not null references polyad.clients (id) on delete cascade,
  state              text   not null default 'draft' check (state in ('draft', 'launched')),
  name               text   not null default '',
  objective          text,
  destination        text,
  currency           text,
  budget_type        text check (budget_type in ('daily', 'lifetime')),
  budget_minor       bigint,
  meta_campaign_id   text unique,
  meta_adset_id      text,
  meta_ad_id         text,
  meta_form_id       text,
  summary            jsonb  not null default '{}'::jsonb,
  draft              jsonb  check (draft is null or pg_column_size(draft) < 200000),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  launched_at        timestamptz
);
create index campaigns_user_id_idx   on polyad.campaigns (user_id, updated_at desc);
create index campaigns_client_id_idx on polyad.campaigns (client_id, updated_at desc);

-- ------------------------------------------------------------------ RLS
alter table polyad.users              enable row level security;
alter table polyad.sessions           enable row level security;
alter table polyad.clients            enable row level security;
alter table polyad.meta_connections   enable row level security;
alter table polyad.client_invites     enable row level security;
alter table polyad.meta_oauth_states  enable row level security;
alter table polyad.meta_oauth_pending enable row level security;
alter table polyad.campaigns          enable row level security;

grant all on all tables in schema polyad to service_role;
grant all on all sequences in schema polyad to service_role;

commit;
