-- Phase C: ECI compliance gate.
--  1. MCMC pre-certification: every political ad needs a certificate from the district/state
--     Media Certification & Monitoring Committee before it runs. One row per certificate.
--  2. Poll schedule per Assembly seat: drives the 48-hour silence period (RPA s.126),
--     which ends when polling closes in that seat.
--  3. Each launched campaign records which certificate covered it (audit trail).

create table polyad.mcmc_certificates (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references polyad.users (id) on delete cascade,
  client_id   bigint not null references polyad.clients (id) on delete cascade,
  cert_no     text   not null check (length(cert_no) between 1 and 80),
  committee   text   not null check (length(committee) between 1 and 120), -- e.g. "District MCMC, Lucknow"
  issued_on   date   not null,
  title       text   not null check (length(title) between 1 and 200),     -- which creative it certifies
  file_path   text,                                                          -- scan of the certificate in polyad-media
  created_at  timestamptz not null default now()
);
create index mcmc_certificates_client_idx on polyad.mcmc_certificates (user_id, client_id, issued_on desc);

create table polyad.poll_schedule (
  user_id     bigint   not null references polyad.users (id) on delete cascade,
  ac_no       integer  not null check (ac_no between 1 and 403),
  phase       smallint check (phase between 1 and 10),
  poll_date   date     not null,
  poll_end    time     not null default '18:00',  -- local (IST) time polling closes
  updated_at  timestamptz not null default now(),
  primary key (user_id, ac_no)
);

alter table polyad.campaigns
  add column mcmc_certificate_id bigint references polyad.mcmc_certificates (id) on delete set null;

alter table polyad.mcmc_certificates enable row level security;
alter table polyad.poll_schedule     enable row level security;
